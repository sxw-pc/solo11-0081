"""Bounded, pre-authorized contract adjudication for a synthetic campaign trial.

The audit only reads columns actually recorded in the trial events
(``assigned`` / ``exposed`` / ``converted`` / ``outcome_observed``) plus the
customer identities generated by :mod:`synthlab.engine`.  It never imports the
structural generator in :mod:`synthlab.campaign_design` to fill in unobserved
potential outcomes: that module supplies independent *test evidence* for the
synthetic design assumptions, not an analysis oracle.

Two pre-authorized purchase contracts are adjudicated:

* ``offer_rollout``  -- pay to mail every household; judged on the
  intention-to-treat (ITT) difference under household random assignment.
* ``reached_only``   -- pay only for incremental customers actually reached;
  judged on the complier effect (Wald/IV estimand: ITT divided by the
  exposure first stage) and only when monotone exposure, the exclusion
  restriction and a non-zero first stage are contractually certified.

Missing conversions are propagated as full intervals (imputed 0 then 1).
A contract is approved only when the whole interval lies strictly above the
minimum effect threshold; it is rejected when the whole interval lies at or
below it, and otherwise the evidence is inconclusive.  Unknowns are never
silently treated as zeros.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Sequence

from .engine import generate_dataset
from .spec.loader import load_dataset

DECISION_APPROVE = "approve"
DECISION_REJECT = "reject"
DECISION_INCONCLUSIVE = "inconclusive"
DECISION_UNIDENTIFIED = "unidentified"

DEFAULT_THRESHOLD = 0.34

OFFER_ROLLOUT = "offer_rollout"
REACHED_ONLY = "reached_only"
CONTRACTS = (OFFER_ROLLOUT, REACHED_ONLY)


class TrialError(ValueError):
    """Raised when trial events cannot be trusted as an experiment."""


def _rate(numerator: float, denominator: int) -> float:
    if denominator == 0:
        raise TrialError("empty denominator: no units in this arm")
    return numerator / denominator


def _adjudicate_interval(low: float, high: float, threshold: float) -> str:
    if low > threshold:
        return DECISION_APPROVE
    if high <= threshold:
        return DECISION_REJECT
    return DECISION_INCONCLUSIVE


def _validate_events(
    customers: Sequence[dict[str, Any]], events: Sequence[dict[str, Any]]
) -> set[str]:
    """Identity and structural checks driven by generated customer identities."""
    generated_ids = [row["customer_id"] for row in customers]
    if len(set(generated_ids)) != len(generated_ids):
        raise TrialError("duplicate generated customer identity")
    ids = set(generated_ids)

    seen: set[str] = set()
    households: dict[str, set[int]] = defaultdict(set)
    for event in events:
        cid = event["customer_id"]
        if cid not in ids:
            raise TrialError(f"trial customer {cid!r} is absent from generated customers")
        if cid in seen:
            raise TrialError(f"duplicate trial event for customer {cid!r}")
        if "household_id" not in event or event["household_id"] in (None, ""):
            raise TrialError(f"trial customer {cid!r} has no household_id; household is the randomization unit")
        seen.add(cid)
        households[event["household_id"]].add(int(event["assigned"]))

    missing_from_trial = ids - seen
    if missing_from_trial:
        raise TrialError(
            "generated customers missing from trial: "
            + ", ".join(sorted(missing_from_trial))
        )

    mixed = [hh for hh, arms in households.items() if len(arms) > 1]
    if mixed:
        raise TrialError(
            "household randomization violated (both arms inside one household): "
            + ", ".join(sorted(mixed))
        )
    return ids


def _arm_records(
    events: Sequence[dict[str, Any]],
) -> dict[int, dict[str, Any]]:
    """Aggregate observed trial columns per assignment arm."""
    arms = {
        0: {"customers": 0, "converted_observed": 0, "outcome_observed": 0, "exposed": 0,
            "missing": 0, "households": set(), "exposed_households": set()},
        1: {"customers": 0, "converted_observed": 0, "outcome_observed": 0, "exposed": 0,
            "missing": 0, "households": set(), "exposed_households": set()},
    }
    for event in events:
        arm = arms[int(event["assigned"])]
        arm["customers"] += 1
        arm["households"].add(event["household_id"])
        if int(event["exposed"]):
            arm["exposed"] += 1
            arm["exposed_households"].add(event["household_id"])
        if bool(event["outcome_observed"]):
            arm["outcome_observed"] += 1
            arm["converted_observed"] += int(event["converted"])
        else:
            arm["missing"] += 1
    return arms


def _bounded_arm_rates(arm: dict[str, Any]) -> dict[str, float]:
    """Conversion rate interval: missing outcomes imputed as 0 (low) then 1 (high)."""
    total = arm["customers"]
    return {
        "rate_low": _rate(arm["converted_observed"], total),
        "rate_high": _rate(arm["converted_observed"] + arm["missing"], total),
    }


def _household_arm_rate_bounds(arm_events: Sequence[dict[str, Any]]) -> tuple[float, float]:
    """Mean of per-household conversion shares, missing outcomes propagated."""
    by_household: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for event in arm_events:
        by_household[event["household_id"]].append(event)
    low_means: list[float] = []
    high_means: list[float] = []
    for rows in by_household.values():
        observed = sum(int(r["converted"]) for r in rows if bool(r["outcome_observed"]))
        missing = sum(1 for r in rows if not bool(r["outcome_observed"]))
        size = len(rows)
        low_means.append(observed / size)
        high_means.append((observed + missing) / size)
    n_households = len(by_household)
    return _rate(sum(low_means), n_households), _rate(sum(high_means), n_households)


def _check_design_evidence(design_evidence: dict[str, Any] | None) -> list[str]:
    """Return reasons the IV design contract cannot be trusted (empty == certified).

    The evidence dict is the trial's own executable design contract; this audit
    does not itself reconstruct unobserved potential outcomes.
    """
    reasons: list[str] = []
    if not design_evidence:
        return ["no design contract evidence supplied for instrumental-variable adjudication"]
    if design_evidence.get("assignment_unit") != "household":
        reasons.append(
            f"assignment unit is {design_evidence.get('assignment_unit')!r}, not 'household'"
        )
    if not design_evidence.get("monotone_exposure"):
        reasons.append("monotone exposure contract not certified")
    if not design_evidence.get("exclusion_restriction"):
        reasons.append("exclusion restriction (assignment affects conversion only via exposure) not certified")
    # Monotonicity is a statement about *potential* exposure under both arms, so
    # it cannot be reconstructed from the single realized exposure column; the
    # executable synthetic design contract must certify it.  Observed control
    # exposure is compatible with monotonicity (always-takers), not evidence of
    # defiers.
    return reasons


def audit_trial(
    customers: Sequence[dict[str, Any]],
    events: Sequence[dict[str, Any]],
    *,
    design_evidence: dict[str, Any] | None = None,
    threshold: float = DEFAULT_THRESHOLD,
) -> dict[str, Any]:
    """Adjudicate the two pre-authorized campaign contracts from observed columns.

    Raises :class:`TrialError` (a ``ValueError``) when the event stream is not
    trustworthy (unknown/duplicate customers, mixed household assignment).
    """
    _validate_events(customers, events)
    arms = _arm_records(events)
    offer, control = arms[1], arms[0]

    # --- observed, customer-level arm statistics with missing-outcome bounds ---
    offer_bounds = _bounded_arm_rates(offer)
    control_bounds = _bounded_arm_rates(control)

    itt_low = offer_bounds["rate_low"] - control_bounds["rate_high"]
    itt_high = offer_bounds["rate_high"] - control_bounds["rate_low"]

    # --- household denominator (the actual randomization unit) ---
    offer_events = [e for e in events if int(e["assigned"]) == 1]
    control_events = [e for e in events if int(e["assigned"]) == 0]
    hh_offer_low, hh_offer_high = _household_arm_rate_bounds(offer_events)
    hh_control_low, hh_control_high = _household_arm_rate_bounds(control_events)
    hh_itt_low = hh_offer_low - hh_control_high
    hh_itt_high = hh_offer_high - hh_control_low

    n_households = len({e["household_id"] for e in events})
    household_first_stage = (
        len(offer["exposed_households"]) / len(offer["households"])
        - len(control["exposed_households"]) / len(control["households"])
    )

    # --- exposure first stage: E[exposed|offer] - E[exposed|control] ---
    exposure_offer = _rate(offer["exposed"], offer["customers"])
    exposure_control = _rate(control["exposed"], control["customers"])
    first_stage = exposure_offer - exposure_control

    # --- naive exposed/unexposed association, retained as a contrast only ---
    naive = {"exposed": [0, 0, 0], "unexposed": [0, 0, 0]}
    for event in events:
        key = "exposed" if int(event["exposed"]) else "unexposed"
        naive[key][2] += 1
        if bool(event["outcome_observed"]):
            naive[key][1] += 1
            naive[key][0] += int(event["converted"])

    # --- contract 1: offer_rollout, ITT on household randomization ---
    offer_rollout = {
        "contract": OFFER_ROLLOUT,
        "estimand": "intention_to_treat",
        "threshold": threshold,
        "effect_interval": [itt_low, itt_high],
        "decision": _adjudicate_interval(itt_low, itt_high, threshold),
    }

    # --- contract 2: reached_only, complier (Wald/IV) effect ---
    design_reasons = _check_design_evidence(design_evidence)
    reached_only: dict[str, Any] = {
        "contract": REACHED_ONLY,
        "estimand": "complier_effect_wald_iv",
        "threshold": threshold,
        "first_stage": first_stage,
    }
    if design_reasons or first_stage <= 0:
        reasons = list(design_reasons)
        if first_stage <= 0:
            reasons.append(
                f"exposure first stage is {first_stage:.4f}: a non-positive first stage "
                "cannot identify a complier effect"
            )
        reached_only.update(
            {
                "effect_interval": None,
                "decision": DECISION_UNIDENTIFIED,
                "reasons": reasons,
            }
        )
    else:
        complier_low = itt_low / first_stage
        complier_high = itt_high / first_stage
        reached_only.update(
            {
                "effect_interval": [complier_low, complier_high],
                "decision": _adjudicate_interval(complier_low, complier_high, threshold),
                "reasons": [],
            }
        )

    return {
        "threshold": threshold,
        "denominators": {
            "customers": sum(arm["customers"] for arm in arms.values()),
            "households": n_households,
            "customers_per_household": (
                sum(arm["customers"] for arm in arms.values()) / n_households
            ),
        },
        "arms": {
            "offer": {
                "customers": offer["customers"],
                "households": len(offer["households"]),
                "exposed_customers": offer["exposed"],
                "outcome_observed": offer["outcome_observed"],
                "missing_outcomes": offer["missing"],
                "converted_observed": offer["converted_observed"],
                "conversion_rate_interval": [
                    offer_bounds["rate_low"], offer_bounds["rate_high"],
                ],
            },
            "control": {
                "customers": control["customers"],
                "households": len(control["households"]),
                "exposed_customers": control["exposed"],
                "outcome_observed": control["outcome_observed"],
                "missing_outcomes": control["missing"],
                "converted_observed": control["converted_observed"],
                "conversion_rate_interval": [
                    control_bounds["rate_low"], control_bounds["rate_high"],
                ],
            },
        },
        "intention_to_treat": {
            "customer_denominator_interval": [itt_low, itt_high],
            "household_denominator_interval": [hh_itt_low, hh_itt_high],
        },
        "first_stage": {
            "customer_denominator": first_stage,
            "household_denominator": household_first_stage,
            "exposure_rate_offer": exposure_offer,
            "exposure_rate_control": exposure_control,
        },
        "naive_exposed_association": {
            "note": "observational contrast only; exposure is self-selected, not randomized",
            "counts": naive,
        },
        "contracts": {
            OFFER_ROLLOUT: offer_rollout,
            REACHED_ONLY: reached_only,
        },
        # Legacy keys kept for callers written against the original audit.
        "counts": naive,
        "unobserved_customers": 0,
    }


def load_design_evidence(payload: dict[str, Any]) -> dict[str, Any]:
    """Map a trial fixture's ``design`` block onto the IV contract evidence flags.

    Only boolean design-contract fields are read; the structural generator is
    never consulted to impute outcomes.
    """
    design = payload.get("design", {})
    return {
        "assignment_unit": design.get("assignment_unit"),
        "monotone_exposure": bool(design.get("monotone_exposure", False)),
        "exclusion_restriction": bool(design.get("exclusion_by_synthetic_rule", False)),
    }


def _format_interval(interval: Sequence[float] | None) -> str:
    if interval is None:
        return "n/a"
    return f"[{interval[0]:.4f}, {interval[1]:.4f}]"


def render_report(result: dict[str, Any]) -> str:
    """Human-readable CLI report that keeps the four estimands distinct."""
    lines: list[str] = []
    arms = result["arms"]
    den = result["denominators"]
    lines.append("synthetic campaign trial audit (bounded sample contract adjudication)")
    lines.append(
        f"denominators: {den['customers']} customers in {den['households']} households "
        f"({den['customers_per_household']:.2f} customers/household; household = randomization unit)"
    )
    for name, arm in arms.items():
        lines.append(
            f"  {name:<7}: {arm['customers']} customers / {arm['households']} households, "
            f"exposed={arm['exposed_customers']}, observed conversions={arm['converted_observed']}"
            f"/{arm['outcome_observed']}, missing={arm['missing_outcomes']}, "
            f"rate bounds={_format_interval(arm['conversion_rate_interval'])}"
        )
    itt = result["intention_to_treat"]
    lines.append(
        "ITT (assignment -> conversion): "
        f"customer {_format_interval(itt['customer_denominator_interval'])}, "
        f"household {_format_interval(itt['household_denominator_interval'])}"
    )
    fs = result["first_stage"]
    lines.append(
        f"first stage (assignment -> exposure): {fs['customer_denominator']:.4f} "
        f"(household denominator {fs['household_denominator']:.4f}); "
        f"exposure rates offer={fs['exposure_rate_offer']:.3f} control={fs['exposure_rate_control']:.3f}"
    )
    naive = result["naive_exposed_association"]["counts"]
    exp_rate = naive["exposed"][0] / naive["exposed"][1] if naive["exposed"][1] else float("nan")
    unexp_rate = naive["unexposed"][0] / naive["unexposed"][1] if naive["unexposed"][1] else float("nan")
    lines.append(
        "naive exposed vs unexposed association (NOT causal; selected exposure): "
        f"{naive['exposed'][0]}/{naive['exposed'][2]} ({exp_rate:.3f}) vs "
        f"{naive['unexposed'][0]}/{naive['unexposed'][2]} ({unexp_rate:.3f})"
    )
    lines.append("pre-authorized budget decisions (strict threshold "
                 f"{result['threshold']:.2f}; missing outcomes propagated as 0..1):")
    for name in CONTRACTS:
        contract = result["contracts"][name]
        line = f"  {name:<13} {contract['estimand']:<24} effect={_format_interval(contract['effect_interval'])}"
        if contract.get("reasons"):
            line += "  decision=" + contract["decision"]
            lines.append(line)
            for reason in contract["reasons"]:
                lines.append(f"      reason: {reason}")
        else:
            lines.append(line + f"  decision={contract['decision']}")
    lines.append(
        "scope: bounded adjudication of this synthetic sample only; "
        "no real-population effect or external statistical guarantee is claimed"
    )
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, default=Path("fixtures/demo/dataset.yaml"))
    parser.add_argument("--trial", type=Path, default=Path("fixtures/campaign/trial.json"))
    parser.add_argument("--json", action="store_true", help="emit machine-readable JSON only")
    args = parser.parse_args(argv)

    data = generate_dataset(load_dataset(args.spec))
    table = data.tables["customers"]
    customers = [dict(zip(table.columns, row)) for row in table.rows]
    payload = json.loads(args.trial.read_text(encoding="utf-8"))
    events = payload["events"]

    evidence = load_design_evidence(payload)
    threshold = float(payload.get("design", {}).get("decision_threshold", DEFAULT_THRESHOLD))
    result = audit_trial(customers, events, design_evidence=evidence, threshold=threshold)

    if args.json:
        print(json.dumps(result, sort_keys=True))
    else:
        print(render_report(result))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
